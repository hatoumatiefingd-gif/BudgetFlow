<h1>Politique de confidentialité</h1>
<p>

        BudgetFlow collecte uniquement les données nécessaires au fonctionnement

        de l'application : nom, adresse e-mail, dépenses et revenus.
</p>
<p>

        Ces données permettent à l'utilisateur de créer un compte,

        se connecter et gérer son budget personnel.
</p>
<p>

        Les données personnelles ne sont pas vendues à des tiers.
</p>
<p>

        Elles sont conservées pendant la durée d'utilisation du compte.

        L'utilisateur peut demander la modification ou la suppression de ses données.
</p>
<p>

        BudgetFlow met en place des mesures de sécurité afin de protéger

        les données personnelles et limiter les accès non autorisés.
</p>
